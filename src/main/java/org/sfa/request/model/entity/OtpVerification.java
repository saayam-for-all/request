package org.sfa.request.model.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

import java.time.ZonedDateTime;

/**
 * One OTP verification cycle for a request (Part 3 of the workflow, issue #95).
 *
 * <p><b>The table does not exist yet.</b> It is proposed to the Database team in
 * {@code db/proposed/otp_verification.sql}. The service runs with {@code ddl-auto=none},
 * so this mapping is only exercised when OTPs are issued or verified; until the table is
 * deployed those calls fail, and nothing else is affected.</p>
 *
 * <p>Codes are never stored: only an HMAC of each code (see {@code OtpCodeHasher}).
 * The task token resumes the paused Step Functions execution and is excluded from
 * {@code toString()} so it never reaches logs.</p>
 */
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
@ToString(exclude = {"requesterCodeHash", "volunteerCodeHash", "taskToken"})
@Entity
@Table(name = "otp_verification", schema = "virginia_dev_saayam_rdbms")
public class OtpVerification {

    /** Random UUID, generated by the service. Also bound into each code's HMAC. */
    @Id
    @Column(name = "otp_verification_id", updatable = false, nullable = false, length = 36)
    private String otpVerificationId;

    @Column(name = "request_id", nullable = false, columnDefinition = "VARCHAR(255)")
    private String requestId;

    @Column(name = "requester_id", nullable = false, columnDefinition = "VARCHAR(255)")
    private String requesterId;

    @Column(name = "lead_volunteer_id", nullable = false, columnDefinition = "VARCHAR(255)")
    private String leadVolunteerId;

    /** HMAC of the code sent to the requester (entered by the lead volunteer). */
    @Column(name = "requester_code_hash", nullable = false, length = 64)
    private String requesterCodeHash;

    /** HMAC of the code sent to the lead volunteer (entered by the requester). */
    @Column(name = "volunteer_code_hash", nullable = false, length = 64)
    private String volunteerCodeHash;

    @Column(name = "requester_code_attempts_remaining", nullable = false)
    private int requesterCodeAttemptsRemaining;

    @Column(name = "volunteer_code_attempts_remaining", nullable = false)
    private int volunteerCodeAttemptsRemaining;

    @Column(name = "requester_code_verified", nullable = false)
    private boolean requesterCodeVerified;

    @Column(name = "volunteer_code_verified", nullable = false)
    private boolean volunteerCodeVerified;

    /** An {@link org.sfa.request.model.enums.OtpVerificationState} name. */
    @Column(name = "state", nullable = false, length = 20)
    private String state;

    @Column(name = "expires_at", nullable = false, columnDefinition = "TIMESTAMP")
    private ZonedDateTime expiresAt;

    /** Step Functions task token of the paused execution waiting on this record. */
    @Column(name = "task_token", nullable = false, columnDefinition = "TEXT")
    private String taskToken;

    @Column(name = "created_at", nullable = false, columnDefinition = "TIMESTAMP")
    private ZonedDateTime createdAt;

    @Column(name = "last_update_date", nullable = false, columnDefinition = "TIMESTAMP")
    private ZonedDateTime lastUpdateDate;
}
