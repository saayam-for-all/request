-- ============================================================================
-- PROPOSED: otp_verification table (Step Functions Part 3, issue #95)
--
-- OWNERSHIP NOTE: the `database` repo owns canonical DDL/DML. This file is the
-- Request microservice's concrete requirement, to be handed to the DBMS team for
-- vetting per the "Changes to the Database, Waiting for Microservice" process --
-- it is NOT to be applied to a shared environment unilaterally.
--
-- WHAT IT STORES: one row per OTP verification cycle. Two codes are issued per
-- cycle: one sent to the requester (entered by the lead volunteer) and one sent
-- to the lead volunteer (entered by the requester). Verification succeeds when
-- both codes have been entered correctly.
--
-- SECURITY: codes are NEVER stored. Each *_code_hash column holds a hex-encoded
-- HMAC-SHA256 of the code, keyed with a server-side secret (OTP_HMAC_SECRET) and
-- bound to the row ID and the code's owner. task_token resumes a paused Step
-- Functions execution and should be treated as a credential (restrict access;
-- consider column encryption).
--
-- Mapped by org.sfa.request.model.entity.OtpVerification.
-- ============================================================================

CREATE TABLE virginia_dev_saayam_rdbms.otp_verification (
    otp_verification_id                 VARCHAR(36)  PRIMARY KEY,           -- UUID, generated by the service
    request_id                          VARCHAR(255) NOT NULL,              -- request.req_id
    requester_id                        VARCHAR(255) NOT NULL,              -- request.req_user_id
    lead_volunteer_id                   VARCHAR(255) NOT NULL,              -- volunteers_assigned.volunteer_id (LEAD)
    requester_code_hash                 VARCHAR(64)  NOT NULL,
    volunteer_code_hash                 VARCHAR(64)  NOT NULL,
    requester_code_attempts_remaining   INTEGER      NOT NULL CHECK (requester_code_attempts_remaining >= 0),
    volunteer_code_attempts_remaining   INTEGER      NOT NULL CHECK (volunteer_code_attempts_remaining >= 0),
    requester_code_verified             BOOLEAN      NOT NULL DEFAULT FALSE,
    volunteer_code_verified             BOOLEAN      NOT NULL DEFAULT FALSE,
    state                               VARCHAR(20)  NOT NULL
        CHECK (state IN ('PENDING', 'VERIFIED', 'EXHAUSTED', 'EXPIRED', 'SUPERSEDED')),
    expires_at                          TIMESTAMP    NOT NULL,
    task_token                          TEXT         NOT NULL,
    created_at                          TIMESTAMP    NOT NULL,
    last_update_date                    TIMESTAMP    NOT NULL,

    CONSTRAINT fk_otp_verification_request
        FOREIGN KEY (request_id) REFERENCES virginia_dev_saayam_rdbms.request (req_id)
);

-- At most one PENDING verification per request. The service marks the previous
-- PENDING row SUPERSEDED before inserting a new one (lead volunteer replaced, or
-- a retry of the issuing step).
CREATE UNIQUE INDEX ux_otp_verification_one_pending_per_request
    ON virginia_dev_saayam_rdbms.otp_verification (request_id)
    WHERE state = 'PENDING';

-- Lookups by request (issuing, verification, history).
CREATE INDEX ix_otp_verification_request_id
    ON virginia_dev_saayam_rdbms.otp_verification (request_id);
